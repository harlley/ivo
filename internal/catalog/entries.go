// targetParam is the one question about what the call acts on. It is shared by
// every tool, so it is asked once and read by whichever tool wins.
func targetParam() Param {
	return Param{
		Kind: ChoiceParam,
		Name: "target",
		QID:  "target_path",
		Desc: "an operand taken from the request or current directory",
		Question: "Which positional operand should selected_program receive after its options? Use its documentation to determine what kind of input it takes. " +
			"The option names are literal candidates from the request or current directory; they are used verbatim. Choose no_argument if the program needs no operand for this request. Words describing the action or desired output are not literal operands. Counts and format qualifiers belong to documented options. For the current project or directory, consult the program documentation: choose . if the program requires that directory as input, and no_argument if it operates on the current directory by default. Select no_argument when options or subcommands express the task.",
		ValuesFor: targetValues,
	}
}

func targetValues(e *env.Env) []Value {
	values := []Value{{
		Key:  ".",
		Desc: "The current directory itself: \"here\", \"this directory\", \"this folder\".",
		Argv: []string{"."},
	}}
	seen := map[string]bool{".": true}

	for _, p := range e.Candidates.Paths {
		if seen[p] {
			continue
		}
		seen[p] = true
		values = append(values, Value{
			Key:  p,
			Desc: "The path " + p + ", which is named in the request and exists on this machine.",
			Argv: []string{p},
		})
	}
	for _, entry := range e.Entries {
		if seen[entry.Name] {
			continue
		}
		seen[entry.Name] = true
		desc := "The file " + entry.Name + " in the current directory."
		if entry.IsDir {
			desc = "The subdirectory " + entry.Name + "/ in the current directory."
		}
		values = append(values, Value{Key: entry.Name, Desc: desc, Argv: []string{entry.Name}})
	}
	// Operands can also be literal text, identifiers, URLs or destinations from
	// the request. They are never generated by the model.
	terms := append([]string{}, e.Candidates.Terms...)
	terms = append(terms, discover.Numbers(e.Request)...)
	for _, word := range discover.WordCandidates(e.Request) {
		if name := e.CommandName(word); name != "" {
			terms = append(terms, name)
		}
	}
	for _, term := range terms {
		if term == "no_argument" || term == NoneKey || seen[term] {
			continue
		}
		seen[term] = true
		values = append(values, Value{Key: term, Desc: "Literal argument from the request: " + term, Argv: []string{term}})
	}
	if len(values) > model.MaxChoiceOptions-2 {
		values = values[:model.MaxChoiceOptions-2]
	}
	return values
}
